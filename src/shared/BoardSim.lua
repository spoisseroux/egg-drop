-- Deterministic board simulation (B0 of the client-run board, artifacts/qa-2026-11-17-v887/
-- client-sim-plan.md "Option B, revised" and B0-plan.md). A port of src/server/BoardSimulation.lua
-- plus the physics and state half of src/server/BoardItems.lua (armed marks, magnet pull, bomb
-- burst, pop, swap, star slots, tier queue) to plain Luau doubles, so the server and every client
-- step the same board to the same bits:
--   * no Vector2/Vector3 (float32) anywhere: balls carry x, y, vx, vy;
--   * no math.sin/cos/exp/pow/atan at runtime: the launch velocity comes from a literal table on a
--     fixed aim grid (BoardSimLaunch, generated by scripts/gen_board_sim_launch.py), and every
--     per-step constant is a precomputed literal; only + - * / math.sqrt math.floor run (IEEE exact);
--   * timers count fixed steps (ticks), never summed seconds;
--   * the step path walks arrays with numeric loops / ipairs only (never pairs over a hash table);
--   * randomness is Random.new(seed):NextInteger (integer PCG), used once in `new`; the board keeps
--     no RNG state, so snapshot/restore is a plain copy.
-- Same rules and order as BoardSimulation. Not used by the live game yet (FeatureFlags.DeckClientSim).
-- Never mark this module --!native until native codegen is proven not to fuse multiply-adds (FMA)
-- on ARM64. Deliberate differences from BoardSimulation: aim on a 400-step grid; the magnet pulls
-- exactly 240 steps (2 s; the old float countdown drifts to 241); the contact gate is 72 steps.
local Shared = script.Parent
local Config = require(Shared.BoardConfig)
local Items = require(Shared.RoundItems)
local Launch = require(Shared.BoardSimLaunch)

local Sim = {}
Sim.Version = 1
Sim.AimSteps = Launch.AimSteps

local DT = Launch.Dt
local GRAVITY_DT = Launch.GravityDt
local DRAG = Launch.Drag
local DIAGONAL = Launch.Diagonal
local VELOCITY = Launch.Velocity
local HALF_WIDTH = Config.Width / 2
local HEIGHT = Config.Height
local BANK = Config.Bank
local MAX_SPEED = Config.MaxSpeed
local MAX_EGGS = Config.MaxEggs
local SPAWN_Y = Config.SpawnY
local TIER_COUNT = #Config.Tiers
local RADIUS = {}
for tier, spec in ipairs(Config.Tiers) do RADIUS[tier] = spec.radius end
-- Seconds in BoardConfig/RoundItems, as whole fixed steps (0.6 s = 72, 2 s = 240).
Sim.GateTicks = math.floor(Config.ContactGateSeconds / Config.FixedStep + 0.5)
Sim.MagnetTicks = math.floor(Items.Magnet.seconds / Config.FixedStep + 0.5)
local GATE_TICKS, MAGNET_TICKS = Sim.GateTicks, Sim.MagnetTicks
local MAGNET_REACH, MAGNET_PULL = Items.Magnet.reach, Items.Magnet.pull
local BOMB_REACH, BOMB_MAX = Items.Bomb.reach, Items.Bomb.max
local ARMABLE = { bomb = true, magnet = true }
-- The generated literals must still describe BoardConfig (re-run scripts/gen_board_sim_launch.py).
assert(DT == Config.FixedStep and GRAVITY_DT == Config.Gravity * Config.FixedStep
	and DRAG == 1 - Config.FixedStep * 0.85 and Launch.Speed == Config.LaunchSpeed
	and Launch.AngleDegrees == Config.LaunchAngleDegrees, "BoardSimLaunch is stale: run scripts/gen_board_sim_launch.py")

-- Item ids as small integers (hash bytes), in RoundItems.Order.
local ITEM_CODE = {}
for index, id in ipairs(Items.Order) do ITEM_CODE[id] = index end

local function addEgg(board, x, y, tier, vx, vy)
	board.serial += 1
	local egg = {
		id = board.serial, tier = tier, radius = RADIUS[tier],
		x = x, y = y, vx = vx or 0, vy = vy or 0,
		hasContact = false, mark = nil, magnetTicks = 0, powerUp = nil,
	}
	table.insert(board.eggs, egg)
	return egg
end

-- options (same keys as BoardSimulation.new): seed, bag, powerUps (heat key), contactGate,
-- kick, bounce, starter; or queue (tiers) + stars (false | item id per slot) as data instead of seed.
function Sim.new(preset, serial, options)
	options = options or {}
	local physics = assert(Config.Presets[preset], "Unknown preset")
	local board = {
		eggs = {}, preset = preset, serial = serial or 0, drops = 0, tick = 0,
		contactGate = options.contactGate == true, dropTicks = 0, fallingId = nil, armed = nil,
		bounce = if options.bounce ~= nil then options.bounce else physics.bounce,
		kick = if options.kick ~= nil then options.kick else physics.kick,
		reach = physics.reach,
		queue = nil, stars = nil, seed = nil, bursts = nil,
	}
	if options.queue ~= nil then
		-- B1: the round host passes the queue and star slots as data (made once on the server,
		-- BoardRoundSim.plan), so no side depends on Random matching across engine builds.
		board.queue = table.clone(options.queue)
		board.stars = if options.stars then table.clone(options.stars) else nil
	elseif options.seed ~= nil then
		local random = Random.new(options.seed)
		board.queue = {}
		for _ = 1, 4 do
			local bag = table.clone(options.bag or { 1, 1, 1, 1, 2, 2 })
			for index = #bag, 2, -1 do
				local other = random:NextInteger(1, index)
				bag[index], bag[other] = bag[other], bag[index]
			end
			for _, tier in ipairs(bag) do table.insert(board.queue, tier) end
		end
		board.seed = options.seed
		-- Star slots as a dense array (false = none), same stream as BoardSimulation.
		if options.powerUps then
			local plan = Items.plan(options.seed, options.powerUps, #board.queue)
			board.stars = table.create(#board.queue, false)
			for slot = 1, #board.queue do board.stars[slot] = plan[slot] or false end
		end
	end
	for _, seed in ipairs(options.starter or Config.Starter) do
		addEgg(board, seed.x, RADIUS[seed.tier], seed.tier)
	end
	return board
end

function Sim.nextTier(board, lookahead)
	local queue = board.queue or Config.Queue
	return queue[(board.drops + (lookahead or 0)) % #queue + 1]
end

function Sim.powerUpAt(board, lookahead)
	if not board.stars or not board.queue then return false end
	return board.stars[(board.drops + (lookahead or 0)) % #board.queue + 1] ~= false
end

function Sim.canDrop(board)
	if not board.contactGate or not board.fallingId or board.dropTicks >= GATE_TICKS then return true end
	for _, egg in ipairs(board.eggs) do
		if egg.id == board.fallingId then return egg.hasContact end
	end
	return true
end

-- The aim grid: index 0..AimSteps for aim 0..1. Nil for an invalid aim.
function Sim.aimIndex(aim)
	if not Config.validAim(aim) then return nil end
	return math.floor(aim * Launch.AimSteps + 0.5)
end
function Sim.launchVelocity(index)
	local row = VELOCITY[index + 1]
	return row[1], row[2]
end

function Sim.drop(board, aim)
	local index = Sim.aimIndex(aim)
	if not index or #board.eggs >= MAX_EGGS or not Sim.canDrop(board) then return false end
	local tier = Sim.nextTier(board)
	local radius = RADIUS[tier]
	for _, egg in ipairs(board.eggs) do
		local dx, dy = egg.x, egg.y - SPAWN_Y
		if math.sqrt(dx * dx + dy * dy) < egg.radius + radius then return false end
	end
	local row = VELOCITY[index + 1]
	local dropped = addEgg(board, 0, SPAWN_Y, tier, row[1], row[2])
	if board.stars and board.queue then
		local slot = board.drops % #board.queue + 1
		dropped.powerUp = board.stars[slot] or nil
		board.stars[slot] = false
	end
	if board.armed then
		dropped.mark, board.armed = board.armed, nil
		if dropped.mark == "magnet" then dropped.magnetTicks = MAGNET_TICKS end
	end
	board.fallingId, board.dropTicks = dropped.id, 0
	board.drops += 1
	return true
end

local function recordImpact(impacts, egg, nx, ny, speed)
	if impacts and speed >= 5 then
		local old = impacts[egg.id]
		if not old or speed > old.speed then impacts[egg.id] = { egg = egg, nx = nx, ny = ny, speed = speed } end
	end
end

local function keepInside(egg, nx, ny, distance, bounce, impacts, contact)
	local overlap = egg.radius - distance
	if overlap <= 0 then return end
	if contact then egg.hasContact = true end
	egg.x += nx * overlap
	egg.y += ny * overlap
	local speed = egg.vx * nx + egg.vy * ny
	if speed < 0 then
		recordImpact(impacts, egg, nx, ny, -speed)
		local factor = 1 + (if speed < -1.8 then bounce else 0)
		egg.vx -= nx * speed * factor
		egg.vy -= ny * speed * factor
	end
end

local function collideWithTray(egg, bounce, impacts)
	keepInside(egg, 1, 0, egg.x + HALF_WIDTH, bounce, impacts)
	keepInside(egg, -1, 0, HALF_WIDTH - egg.x, bounce, impacts)
	keepInside(egg, 0, 1, egg.y, bounce, impacts, true)
	keepInside(egg, 0, -1, HEIGHT - egg.y, bounce, impacts)
	keepInside(egg, DIAGONAL, DIAGONAL, (egg.x + HALF_WIDTH + egg.y - BANK) * DIAGONAL, bounce, impacts, true)
	keepInside(egg, -DIAGONAL, DIAGONAL, (HALF_WIDTH - egg.x + egg.y - BANK) * DIAGONAL, bounce, impacts, true)
end

-- BoardConfig.advanceFlight on doubles: gravity, the speed cap, drag, then move.
local function advance(egg)
	local vx, vy = egg.vx, egg.vy - GRAVITY_DT
	local speed = math.sqrt(vx * vx + vy * vy)
	if speed > MAX_SPEED then vx, vy = vx / speed * MAX_SPEED, vy / speed * MAX_SPEED end
	vx, vy = vx * DRAG, vy * DRAG
	egg.vx, egg.vy = vx, vy
	egg.x += vx * DT
	egg.y += vy * DT
end

local function merge(board, firstIndex, secondIndex)
	local eggs = board.eggs
	local first, second = eggs[firstIndex], eggs[secondIndex]
	local x, y = (first.x + second.x) / 2, (first.y + second.y) / 2
	local vx = (first.vx + second.vx) * 0.38
	local vy = (first.vy + second.vy) * 0.38 + 2
	table.remove(eggs, secondIndex)
	table.remove(eggs, firstIndex)
	local cleared = first.tier == TIER_COUNT
	local powerUps = nil
	if first.powerUp then powerUps = { first.powerUp } end
	if second.powerUp then powerUps = powerUps or {}; table.insert(powerUps, second.powerUp) end
	local result
	if not cleared then
		result = addEgg(board, x, y, first.tier + 1, vx, vy)
		collideWithTray(result, 0, nil)
		x, y = result.x, result.y
	end
	local kick, reach = board.kick, board.reach
	for _, egg in ipairs(eggs) do
		if egg ~= result then
			local dx, dy = egg.x - x, egg.y - y
			local distance = math.sqrt(dx * dx + dy * dy)
			if distance > 0 and distance < reach then
				local strength = kick * (1 - distance / reach)
				egg.vx += dx / distance * strength
				egg.vy += dy / distance * strength
			end
		end
	end
	return {
		x = x, y = y, tier = if result then result.tier else first.tier,
		fromX = first.x, fromY = first.y, otherX = second.x, otherY = second.y,
		id = if result then result.id else nil, firstId = first.id, secondId = second.id,
		cleared = cleared, powerUp = first.powerUp or second.powerUp, powerUps = powerUps,
	}
end

local function resolvePairs(board, merged, impacts)
	local eggs = board.eggs
	local bounceKnob = board.bounce
	for firstIndex = 1, #eggs - 1 do
		local first = eggs[firstIndex]
		for secondIndex = firstIndex + 1, #eggs do
			local second = eggs[secondIndex]
			local dx, dy = second.x - first.x, second.y - first.y
			local distance = math.sqrt(dx * dx + dy * dy)
			local overlap = first.radius + second.radius - distance
			if overlap > 0 then
				first.hasContact, second.hasContact = true, true
				local nx, ny = 1, 0
				if distance > 0 then nx, ny = dx / distance, dy / distance end
				local speed = (second.vx - first.vx) * nx + (second.vy - first.vy) * ny
				if first.tier == second.tier and first.mark ~= "bomb" and second.mark ~= "bomb" then
					table.insert(merged, merge(board, firstIndex, secondIndex))
					return true
				end
				local half = overlap / 2
				first.x -= nx * half; first.y -= ny * half
				second.x += nx * half; second.y += ny * half
				if speed < 0 then
					recordImpact(impacts, first, -nx, -ny, -speed)
					recordImpact(impacts, second, nx, ny, -speed)
					local bounce = if speed < -1.8 then bounceKnob else 0
					local impulse = speed * (1 + bounce) / 2
					local ix, iy = nx * impulse, ny * impulse
					first.vx += ix; first.vy += iy
					second.vx -= ix; second.vy -= iy
				end
			end
		end
	end
	return false
end

-- ── Items (rules from BoardItems; the belt, sequence and budget stay on the server) ──
local function removeEggs(board, victims)
	local gone = {}
	for _, egg in ipairs(victims) do gone[egg] = true end
	for index = #board.eggs, 1, -1 do
		if gone[board.eggs[index]] then table.remove(board.eggs, index) end
	end
end

function Sim.swapNext(board)
	if not board.queue then return false end
	local n = #board.queue
	local a, b = board.drops % n + 1, (board.drops + 1) % n + 1
	if a == b then return false end
	board.queue[a], board.queue[b] = board.queue[b], board.queue[a]
	if board.stars then board.stars[a], board.stars[b] = board.stars[b], board.stars[a] end
	return true
end

function Sim.popTarget(board)
	local best, top = nil, -math.huge
	for _, egg in ipairs(board.eggs) do
		if egg.hasContact and egg.y + egg.radius > top then best, top = egg, egg.y + egg.radius end
	end
	return best
end
function Sim.pop(board)
	local target = Sim.popTarget(board)
	if not target then return nil end
	removeEggs(board, { target })
	return target
end

-- Bomb or Magnet rides on the next drop. False when one is already armed.
function Sim.arm(board, id)
	if board.armed or not ARMABLE[id] then return false end
	board.armed = id
	return true
end

function Sim.burst(board, bomb)
	local candidates = {}
	for _, egg in ipairs(board.eggs) do
		if egg ~= bomb then
			local dx, dy = egg.x - bomb.x, egg.y - bomb.y
			local distance = math.sqrt(dx * dx + dy * dy)
			if distance <= bomb.radius + BOMB_REACH then table.insert(candidates, { egg = egg, distance = distance }) end
		end
	end
	table.sort(candidates, function(a, b)
		if a.distance ~= b.distance then return a.distance < b.distance end
		return a.egg.id < b.egg.id
	end)
	local victims = { bomb }
	for index = 1, math.min(BOMB_MAX, #candidates) do table.insert(victims, candidates[index].egg) end
	removeEggs(board, victims)
	local ids = {}
	for _, egg in ipairs(victims) do table.insert(ids, egg.id) end
	board.bursts = board.bursts or {}
	table.insert(board.bursts, { x = bomb.x, y = bomb.y, ids = ids })
	return victims
end

local function pullMagnets(board)
	local eggs = board.eggs
	for _, magnet in ipairs(eggs) do
		if magnet.mark == "magnet" and magnet.hasContact and magnet.magnetTicks > 0 then
			magnet.magnetTicks -= 1
			for _, other in ipairs(eggs) do
				if other ~= magnet and other.tier == magnet.tier then
					local dx, dy = magnet.x - other.x, magnet.y - other.y
					local distance = math.sqrt(dx * dx + dy * dy)
					if distance > 0 and distance < MAGNET_REACH then
						other.vx += dx / distance * MAGNET_PULL * DT
						other.vy += dy / distance * MAGNET_PULL * DT
					end
				end
			end
		end
	end
end

-- One fixed step (Config.FixedStep of simulation time). `merged` receives merge records,
-- `impacts` (optional) the strongest impact per ball id this step.
function Sim.step(board, merged, impacts)
	merged = merged or {}
	local bounce = board.bounce
	board.dropTicks += 1
	pullMagnets(board)
	for _, egg in ipairs(board.eggs) do
		advance(egg)
		collideWithTray(egg, bounce, impacts)
	end
	for _ = 1, 3 do
		local didMerge = resolvePairs(board, merged, impacts)
		for _, egg in ipairs(board.eggs) do collideWithTray(egg, bounce, impacts) end
		if not didMerge then break end
	end
	for index = #board.eggs, 1, -1 do
		local egg = board.eggs[index]
		if egg and egg.mark == "bomb" and egg.hasContact then Sim.burst(board, egg) end
	end
	board.tick += 1
	return merged
end

-- One logged input: {tick=, kind="drop", aim=} | {kind="swap"} | {kind="pop"} | {kind="arm", item=}.
-- Returns whether the board accepted it.
function Sim.apply(board, input)
	local kind = input.kind
	if kind == "drop" then return Sim.drop(board, input.aim)
	elseif kind == "swap" then return Sim.swapNext(board)
	elseif kind == "pop" then return Sim.pop(board) ~= nil
	elseif kind == "arm" then return Sim.arm(board, input.item)
	end
	return false
end

-- ── Hash, snapshot, replay ───────────────────────────────────────────────
local function flag(value) return if value then 1 else 0 end
local function markCode(mark) return if mark == "bomb" then 1 elseif mark == "magnet" then 2 else 0 end

-- The canonical byte string of the whole board state (exact double bits via "<d").
function Sim.encode(board)
	local parts = {}
	local queue = board.queue
	local n = if queue then #queue else 0
	table.insert(parts, string.pack("<i4i4i4i4i4BBB", board.tick, board.serial, board.drops,
		board.fallingId or -1, board.dropTicks, flag(board.contactGate), markCode(board.armed), n))
	table.insert(parts, string.pack("<ddd", board.bounce, board.kick, board.reach))
	for index = 1, n do
		local star = board.stars and board.stars[index]
		table.insert(parts, string.pack("<BB", queue[index], if star then ITEM_CODE[star] or 255 else 0))
	end
	local eggs = board.eggs
	table.insert(parts, string.pack("<i4", #eggs))
	for _, egg in ipairs(eggs) do
		table.insert(parts, string.pack("<i4BBdddddBi4B", egg.id, egg.tier, flag(egg.hasContact),
			egg.radius, egg.x, egg.y, egg.vx, egg.vy, markCode(egg.mark), egg.magnetTicks,
			if egg.powerUp then ITEM_CODE[egg.powerUp] or 255 else 0))
	end
	local bursts = board.bursts
	table.insert(parts, string.pack("<i4", if bursts then #bursts else 0))
	for _, burst in ipairs(bursts or {}) do
		table.insert(parts, string.pack("<ddi4", burst.x, burst.y, #burst.ids))
		for _, id in ipairs(burst.ids) do table.insert(parts, string.pack("<i4", id)) end
	end
	return table.concat(parts)
end

-- Two 32-bit lanes over 4-byte words: FNV-1a (prime 2^24 + 403, multiplied exactly in
-- doubles) and a polynomial (*31). 16 hex characters.
function Sim.hashBytes(bytes)
	local length = #bytes
	local padded = buffer.create(length + (4 - length % 4) % 4)
	buffer.writestring(padded, 0, bytes)
	local h, g = 2166136261, length
	for offset = 0, buffer.len(padded) - 4, 4 do
		local word = buffer.readu32(padded, offset)
		h = bit32.bxor(h, word)
		h = (bit32.lshift(h, 24) + h * 403) % 4294967296
		g = (g * 31 + word) % 4294967296
	end
	return string.format("%08x%08x", h, g)
end

function Sim.hash(board)
	return Sim.hashBytes(Sim.encode(board))
end

-- Deep copy of plain data (board, balls, queue, stars, bursts). No functions, no cycles.
local function copy(value)
	if type(value) ~= "table" then return value end
	local result = {}
	for key, item in pairs(value) do result[key] = copy(item) end
	return result
end
-- Full state copies, for rollback: restore(snapshot) returns a fresh board each time, so a
-- snapshot can be restored more than once.
function Sim.snapshot(board) return copy(board) end
function Sim.restore(snapshot) return copy(snapshot) end

-- Replays an input log from a fresh board. inputs are ordered by tick; an input at tick t
-- applies after t steps, before step t + 1. options: hashEvery (60), the Sim.new options
-- (seed is the argument), onStep(board, merged), yieldEvery + yield (called every yieldEvery
-- ticks, for chunked work). Returns { hashes = {...}, final = <hash>, board, accepted, refused }.
-- `hashes` holds the hash after every hashEvery-th tick and after the last.
function Sim.replay(seed, preset, inputs, ticks, options)
	options = options or {}
	local simOptions = {}
	for key, value in pairs(options) do simOptions[key] = value end
	simOptions.seed = seed
	local board = Sim.new(preset, options.serial or 0, simOptions)
	local hashEvery = options.hashEvery or 60
	local hashes, accepted, refused = {}, 0, 0
	local nextInput = 1
	local merged = {}
	for tick = 0, ticks - 1 do
		local input = inputs[nextInput]
		while input and input.tick <= tick do
			assert(input.tick == tick, "inputs must be ordered by tick")
			if Sim.apply(board, input) then accepted += 1 else refused += 1 end
			nextInput += 1
			input = inputs[nextInput]
		end
		table.clear(merged)
		Sim.step(board, merged, nil)
		if options.onStep then options.onStep(board, merged) end
		board.bursts = nil
		if board.tick % hashEvery == 0 or tick == ticks - 1 then table.insert(hashes, Sim.hash(board)) end
		if options.yield and options.yieldEvery and board.tick % options.yieldEvery == 0 then options.yield() end
	end
	return { hashes = hashes, final = hashes[#hashes], board = board, accepted = accepted, refused = refused }
end

return table.freeze(Sim)
