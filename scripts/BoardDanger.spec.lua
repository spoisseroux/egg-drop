-- Studio Client. The round danger state machine (UI-SPEC-REDESIGN-MENUS 6.3 and
-- BUILD-PLAN architect change 4): OverflowPressure / OverflowGraceLeft -> calm /
-- near / over, line colour, drain fraction, red window, haze, chip copy, one entry
-- cue and one cleared chime. Pure helpers plus an isolated view on a scratch frame;
-- never touches the live board or its attributes.
-- Usage: require(PlayerScripts.Client.ZZSpecs.BoardDanger)(PlayerScripts.Client, PlayerGui)
return function(client,parent)
 local Danger=require(client.BoardDanger)
 local cases={};local function test(name,run)run();table.insert(cases,name)end
 local function near(a,b,eps)return math.abs(a-b)<=(eps or 1e-6)end
 local root=Instance.new("Frame");root.Name="_BoardDangerSpec";root.Size=UDim2.fromOffset(163,277);root.BackgroundTransparency=1;root.Parent=parent
 local ok,problem=pcall(function()
  test("state comes from pressure and grace left",function()
   assert(Danger.classify(0,0)=="calm"and Danger.classify(nil,nil)=="calm")
   assert(Danger.classify(.4,0)=="near"and Danger.classify(.85,0)=="near")
   assert(Danger.classify(.5,.8)=="over"and Danger.classify(0,.01)=="over","grace left alone means over")
  end)
  test("line colour: white calm, amber near and over, red only in the last 0.35 s",function()
   assert(Danger.lineColor("calm",0)==Color3.new(1,1,1))
   assert(Danger.lineColor("near",0)==Color3.fromHex("#FFB02E"))
   assert(Danger.lineColor("over",1.1)==Color3.fromHex("#FFB02E")and Danger.lineColor("over",.36)==Color3.fromHex("#FFB02E"))
   assert(Danger.lineColor("over",.35)==Color3.fromHex("#FF5A6E")and Danger.lineColor("over",.01)==Color3.fromHex("#FF5A6E"))
   assert(not Danger.isRed("near",.2)and not Danger.isRed("over",0)and Danger.isRed("over",.2))
   assert(Danger.RedWindow==.35)
  end)
  test("drain fraction is grace left over grace; Reduced Motion steps once per second",function()
   assert(near(Danger.drain(1.1,1.1,false),1)and near(Danger.drain(.55,1.1,false),.5)and Danger.drain(0,1.1,false)==0)
   assert(near(Danger.drain(1.5,1.1,false),1),"clamped to a full line")
   assert(Danger.drain(.5,0,false)==0 and Danger.drain(.5,nil,false)==0)
   -- 1.1 s grace: two steps; 3 s trial grace: three steps.
   assert(Danger.drain(1.05,1.1,true)==1 and Danger.drain(.9,1.1,true)==.5 and Danger.drain(.1,1.1,true)==.5)
   assert(Danger.drain(2.9,3,true)==1 and near(Danger.drain(1.7,3,true),2/3)and near(Danger.drain(.3,3,true),1/3))
  end)
  test("haze alpha and chip copy follow the state",function()
   assert(Danger.hazeAlpha("calm",0)==0 and Danger.hazeAlpha("near",0)==0)
   assert(Danger.hazeAlpha("over",1)==.27 and Danger.hazeAlpha("over",.3)==.43)
   local t,d=Danger.chipText("over",1);assert(t=="Stack too high"and d=="Merge to clear")
   t,d=Danger.chipText("over",.2);assert(t=="Stack too high"and d=="Merge now")
   t,d=Danger.chipText("calm",0,true);assert(t=="Safe"and d=="")
   t=Danger.chipText("near",0);assert(t=="")
  end)
  local plays={}
  local audio={play=function(_,name)table.insert(plays,name);return true end}
  local view=Danger.new(root,{audio=audio});view:place(4,155,90)
  test("calm shows the dashed white line and the FILL LINE tag only",function()
   view:update(0,0,0,false,true,false)
   assert(view.state=="calm"and view.dashes.Visible and not view.bar.Visible and view.tag.Visible and view.tag.Text=="FILL LINE")
   assert(not view.chip.Visible and not view.haze.Visible and #plays==0)
   assert(near(view.dashes:GetChildren()[1].BackgroundTransparency,.76),"calm dashes are white 24%")
  end)
  test("near is a solid amber line with an amber tag, no chip, no sound",function()
   view:update(.5,0,.1,false,true,false)
   assert(view.state=="near"and view.bar.Visible and not view.dashes.Visible and view.bar.BackgroundColor3==Danger.Amber)
   assert(view.tag.Visible and view.tag.TextColor3==Danger.Amber and not view.chip.Visible and #plays==0)
  end)
  test("over: one entry cue, chip, haze fades in, the line drains between publishes",function()
   view:update(.6,1.1,1,false,true,false)
   assert(view.state=="over"and #plays==1 and plays[1]=="danger_enter","entry cue plays once")
   assert(view.chip.Visible and view.title.Text=="Stack too high"and view.detail.Text=="Merge to clear"and not view.tag.Visible)
   for frame=1,12 do view:update(.6,1.1,1+frame/60,false,true,false)end
   assert(#plays==1,"no repeating blip")
   assert(view.haze.Visible and near(1-view.haze.BackgroundTransparency,.27,.011),"haze reaches 27% after 0.2 s")
   assert(view.fraction<1 and view.fraction>.75,"line drains locally while the server value is unchanged: "..view.fraction)
   assert(near(view.bar.Size.X.Scale,view.fraction,1e-4)and view.bar.Size.Y.Offset==4,"UDim scale is float32")
  end)
  test("last 0.35 s turns line, haze and chip copy red",function()
   view:update(.9,.3,1.3,false,true,false)
   assert(view.bar.BackgroundColor3==Danger.Red and view.haze.BackgroundColor3==Danger.Red and view.detail.Text=="Merge now")
   assert(view.chipStroke.Color==Danger.Red and #plays==1)
  end)
  test("clearing plays the chime once, flashes white and shows Safe for 0.6 s",function()
   view:update(.4,0,1.4,false,true,false)
   assert(view.state=="near"and #plays==2 and plays[2]=="danger_clear")
   assert(view.chip.Visible and view.title.Text=="Safe"and view.bar.BackgroundColor3==Color3.new(1,1,1))
   view:update(.4,0,1.65,false,true,false);assert(view.bar.BackgroundColor3==Danger.Amber,"flash lasts 0.2 s")
   view:update(.4,0,2.05,false,true,false);assert(not view.chip.Visible and view.tag.Visible,"Safe lasts 0.6 s")
   for frame=1,30 do view:update(.4,0,2.05+frame/60,false,true,false)end
   assert(not view.haze.Visible and #plays==2)
  end)
  test("a lost round never reads as cleared; a hidden board plays no cues",function()
   view:update(.6,1.1,3,false,false,false);assert(view.state=="over"and #plays==2,"no cue while not presented")
   view:update(0,0,3.1,false,true,true);assert(#plays==2 and not view.chip.Visible,"no chime when the round ended")
  end)
  test("Reduced Motion: no haze fade, no pulse, the line steps",function()
   local still=Danger.new(root,{audio=audio});still:place(4,155,90)
   still:update(.6,1.1,10,true,false,false)
   assert(near(1-still.haze.BackgroundTransparency,.27,.011),"haze is instant")
   assert(still.fraction==1,"full line at entry")
   local glow=still.glow.BackgroundTransparency;still:update(.6,1.1,10.3,true,false,false)
   assert(still.glow.BackgroundTransparency==glow,"no pulse")
   -- 0.8 s left of 1.1 s: one whole second is gone, so the line has stepped to half.
   assert(still.fraction==.5,"stepped fraction="..still.fraction)
   still:destroy()
  end)
  test("chip fits the 163 px phone board and straddles the line",function()
   local chip=view.chip;assert(chip.Size.X.Offset<=155-12+.01 and chip.Size.Y.Offset==40)
   local center=chip.Position.Y.Offset;assert(center-20<90 and center+20>90,"chip straddles the line")
   assert(view.title.TextSize>=12 and view.detail.TextSize>=12 and view.tag.TextSize>=12,"text floor 12")
  end)
  view:destroy()
 end)
 root:Destroy();assert(ok,problem)
 return{passed=#cases,cases=cases}
end
