"""Build the Bunny's runtime rig definition, its PetAssets template and the Stat Snack pack.

Inputs:
- assets/art-source/pets/bunny-rig-proposal.lua: Fable's rig data in runtime axes (pieces, anchors,
  anchor frames, anchorDeltaFromBear, earPose, palette, colour roles). Generated by build_bunny.py.
- assets/garden-babies/bunny-studio-import.json: mesh ids, raw 100x MeshSize and template positions
  from the actual Open Cloud upload (InsertService:LoadAsset in Studio Edit), and texture image ids.
- assets/snacks/snack-studio-import.json: the same for the three Stat Snack FBXs.

Outputs:
- src/shared/BunnyRigDefinition.lua: the proposal table, marked live, with `legacyId = "blip"`
  (the account id: the never-granted earned slot, bit 0x80) and `fitFrom = "pip"` (the rig whose
  attachment meshes it wears). PetRigDefinitions copies the Bear's keys named in inheritFromBear.
- PetAssets.rbxmx: the `Bunny` Model between the BUNNY markers. Template axes are the import's
  (front -Z); GardenPetVisual turns it by pi once. Size = MeshSize/100, InitialSize = raw MeshSize.
  Eyes take TextureID; the mouth and blush are cut-outs (SurfaceAppearance, AlphaMode Transparency).
- assets/snacks/SnackAssets.rbxmx: one Model per size (Nibble, Snack, Feast) with its pieces.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PETS = ROOT / "assets" / "garden-babies"
PROPOSAL = ROOT / "assets" / "art-source" / "pets" / "bunny-rig-proposal.lua"
BUNNY_IMPORT = json.loads((PETS / "bunny-studio-import.json").read_text())
SNACK_DIR = ROOT / "assets" / "snacks"
SNACK_IMPORT = json.loads((SNACK_DIR / "snack-studio-import.json").read_text())

BUNNY_PIECES = ["Body", "Head", "EarL", "EarR", "EarInnerL", "EarInnerR", "Muzzle", "Nose", "MouthSmile",
                "EyeL", "EyeR", "BlushL", "BlushR", "Tail", "HandL", "HandR", "FootL", "FootR", "CharmDot"]
CUTOUTS = {"MouthSmile": "mouth", "BlushL": "blush", "BlushR": "blush"}
TEXTURED = {"EyeL": "eye", "EyeR": "eye"}


def lua_definition() -> str:
    text = PROPOSAL.read_text(encoding="utf-8")
    body = text[text.index("return {"):]
    body = body.replace('  status = "PROPOSAL 2026-11-19: data only, not wired into src/",\n',
                        '  legacyId = "blip",\n  fitFrom = "pip",\n', 1)
    assert 'legacyId = "blip"' in body, "proposal layout changed"
    return ("-- Generated by scripts/build_bunny_assets.py from assets/art-source/pets/bunny-rig-proposal.lua (Fable).\n"
            "-- Do not edit by hand. Runtime axes: front +Z, up +Y, paws at the origin. Account id `blip` (the\n"
            "-- earned slot, bit 0x80) renders this rig. PetRigDefinitions copies the Bear's keys named in\n"
            "-- inheritFromBear; anchorDeltaFromBear and earPose are read by PetAttachments / GardenPetVisual.\n"
            + body)


def vec(tag, v, indent="          "):
    return (f"{indent}<Vector3 name=\"{tag}\">\n{indent}  <X>{v[0]!r}</X>\n{indent}  <Y>{v[1]!r}</Y>\n"
            f"{indent}  <Z>{v[2]!r}</Z>\n{indent}</Vector3>\n")


def frame(pos, indent="          "):
    return (f"{indent}<CoordinateFrame name=\"CFrame\">\n"
            f"{indent}  <X>{pos[0]!r}</X>\n{indent}  <Y>{pos[1]!r}</Y>\n{indent}  <Z>{pos[2]!r}</Z>\n"
            f"{indent}  <R00>1</R00>\n{indent}  <R01>0</R01>\n{indent}  <R02>0</R02>\n{indent}  <R10>0</R10>\n"
            f"{indent}  <R11>1</R11>\n{indent}  <R12>0</R12>\n{indent}  <R20>0</R20>\n{indent}  <R21>0</R21>\n"
            f"{indent}  <R22>1</R22>\n{indent}</CoordinateFrame>\n")


def mesh_part(ref, name, p, texture="", cutout="", color=None):
    raw = p["ms"]
    size = [raw[0] / 100, raw[1] / 100, raw[2] / 100]
    pos = [round(c / 100, 6) for c in p["pos"]]
    ink = ""
    if cutout:
        ink = (f"        <Item class=\"SurfaceAppearance\" referent=\"{ref}Ink\">\n          <Properties>\n"
               "            <string name=\"Name\">CutOut</string>\n            <token name=\"AlphaMode\">1</token>\n"
               f"            <Content name=\"ColorMap\">\n              <url>{cutout}</url>\n            </Content>\n"
               "          </Properties>\n        </Item>\n")
    color_xml = ""
    if color:
        r, g, b = (int(color[i:i + 2], 16) for i in (1, 3, 5))
        color_xml = f"          <Color3uint8 name=\"Color3uint8\">{(255 << 24) | (r << 16) | (g << 8) | b}</Color3uint8>\n"
    return (f"      <Item class=\"MeshPart\" referent=\"{ref}\">\n        <Properties>\n"
            f"          <string name=\"Name\">{name}</string>\n"
            f"          <Content name=\"MeshId\">\n            <url>{p['id']}</url>\n          </Content>\n"
            "          <Content name=\"TextureID\">\n            " + (f"<url>{texture}</url>" if texture else "<url />")
            + "\n          </Content>\n" + vec("Size", size) + vec("InitialSize", raw) + frame(pos) + color_xml +
            "          <bool name=\"Anchored\">true</bool>\n          <bool name=\"CanCollide\">false</bool>\n"
            "          <bool name=\"CanTouch\">false</bool>\n          <bool name=\"CanQuery\">false</bool>\n"
            "          <bool name=\"CastShadow\">false</bool>\n"
            "        </Properties>\n" + ink + "      </Item>\n")


def origin(ref):
    return ("      <Item class=\"CFrameValue\" referent=\"" + ref + "\">\n        <Properties>\n"
            "          <string name=\"Name\">PawsOrigin</string>\n"
            "          <CoordinateFrame name=\"Value\">\n            <X>0</X>\n            <Y>0</Y>\n            <Z>0</Z>\n"
            "            <R00>1</R00>\n            <R01>0</R01>\n            <R02>0</R02>\n            <R10>0</R10>\n            <R11>1</R11>\n"
            "            <R12>0</R12>\n            <R20>0</R20>\n            <R21>0</R21>\n            <R22>1</R22>\n          </CoordinateFrame>\n"
            "        </Properties>\n      </Item>\n")


def bunny_block() -> str:
    tex = BUNNY_IMPORT["textures"]
    out = ["    <!-- BEGIN BUNNY (generated by scripts/build_bunny_assets.py) -->\n",
           "    <Item class=\"Model\" referent=\"Bunny\">\n      <Properties>\n        <string name=\"Name\">Bunny</string>\n      </Properties>\n",
           origin("BunnyOrigin")]
    for index, name in enumerate(BUNNY_PIECES):
        key = "Bunny__" + name
        out.append(mesh_part(f"Bunny{index}", key, BUNNY_IMPORT["parts"][key],
                             texture=tex[TEXTURED[name]] if name in TEXTURED else "",
                             cutout=tex[CUTOUTS[name]] if name in CUTOUTS else ""))
    out.append("    </Item>\n    <!-- END BUNNY -->\n")
    # Fit reasons in the source manifest: every piece in the template, no strays.
    assert set("Bunny__" + n for n in BUNNY_PIECES) == set(BUNNY_IMPORT["parts"]), "bunny import pieces differ"
    return "".join(out)


def snack_pack() -> str:
    tex = SNACK_IMPORT["textures"]
    out = ["<roblox version=\"4\">\n  <Item class=\"Folder\" referent=\"Snacks\">\n    <Properties>\n"
           "      <string name=\"Name\">SnackAssets</string>\n    </Properties>\n"
           "    <!-- Generated by scripts/build_bunny_assets.py from assets/snacks/snack-studio-import.json. -->\n"]
    for size in ("Nibble", "Snack", "Feast"):
        out.append(f"    <Item class=\"Model\" referent=\"Snack{size}\">\n      <Properties>\n"
                   f"        <string name=\"Name\">{size}</string>\n      </Properties>\n")
        for piece in ("Biscuit", "Icing", "Pearls"):
            key = f"StatSnack_{size}__{piece}"
            p = SNACK_IMPORT["parts"].get(key)
            if not p:
                continue
            out.append(mesh_part(f"Snack{size}{piece}", piece, p,
                                 texture=tex["biscuit"] if piece == "Biscuit" else "",
                                 color="#FFF6E9" if piece == "Pearls" else ("#FFFFFF" if piece == "Biscuit" else None)))
        out.append("    </Item>\n")
    out.append("  </Item>\n</roblox>\n")
    return "".join(out)


def main() -> None:
    (ROOT / "src" / "shared" / "BunnyRigDefinition.lua").write_text(lua_definition(), encoding="utf-8", newline="\n")
    path = PETS / "PetAssets.rbxmx"
    text = path.read_text().replace("\r\n", "\n")
    block = bunny_block()
    if "<!-- BEGIN BUNNY" in text:
        start = text.index("    <!-- BEGIN BUNNY")
        end = text.index("<!-- END BUNNY -->") + len("<!-- END BUNNY -->\n")
        text = text[:start] + block + text[end:]
    else:
        marker = "    <!-- END BEAR ATTACHMENTS -->\n"
        assert marker in text, "PetAssets.rbxmx layout changed"
        text = text.replace(marker, marker + block, 1)
    path.write_text(text, newline="\r\n")  # the file is CRLF
    (SNACK_DIR / "SnackAssets.rbxmx").write_text(snack_pack(), newline="\n")
    print("wrote BunnyRigDefinition.lua, the Bunny template and SnackAssets.rbxmx")


if __name__ == "__main__":
    main()
