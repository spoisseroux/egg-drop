-- v2 S3: pure rules of the stats UI (StatToasts, StatsPanel, FocusRow). Studio Edit or Client.
-- Usage: require(<copy>)(function(name) return require(<Client folder>[name]) end)
-- (in Edit, pass a require that clones the module beside the original, so edits are seen).
return function(req)
 local Toasts=req("StatToasts");local Panel=req("StatsPanel");local Row=req("FocusRow")
 local cases={};local function test(name,run)run();table.insert(cases,name)end
 test("level-ups: first sight records only; higher levels show; merged in stat order",function()
  local a=Toasts.levels({pets={pip={xp={power=10}}}})
  local b=Toasts.levels({pets={pip={xp={power=40,energy=20}},kit={xp={power=999}}}})
  local ups=Toasts.diff(a,b)
  assert(#ups==2 and ups[1].stat=="power"and ups[1].level==3 and ups[2].stat=="energy"and ups[2].level==2,"two ups on the known pet only")
  assert(#Toasts.diff(nil,b)==0 and Toasts.levels(nil)==nil,"no snapshot, no ups")
  local pending=Toasts.merge(nil,ups);pending=Toasts.merge(pending,{{stat="power",level=2}})
  assert(pending.power==3,"merge keeps the highest level")
  assert(Toasts.line(pending)=="Power 3, Energy 2","line in Order: "..Toasts.line(pending))
 end)
 test("a line too wide for the rail caps to the first stat and a count",function()
  local text=Toasts.capped({heart=12,power=15,energy=12},function(t)return #t<12 end)
  assert(text=="Heart 12 +2",text)
  assert(Toasts.capped({power=15},function()return false end)=="Power 15","one stat is never capped")
 end)
 test("held lines wait, then merge into one rail line; a too-wide merge starts a new line",function()
  local queued={}
  local rail={enqueue=function(_,key,data)queued[key]=data;return{cancel=function()queued[key]=nil end}end}
  local held=true
  local clock=0
  local t=Toasts.new({rail=rail,owner=nil,held=function()return held end,fits=function(text)return #text<=20 end,now=function()return clock end})
  t:update({pets={pip={xp={power=0}}}})
  t:update({pets={pip={xp={power=40}}}})
  assert(next(queued)==nil and t.pending.power==3,"held during a round")
  held=false;t:flush()
  local key,data=next(queued);assert(data.text=="Power 3",tostring(data and data.text))
  clock=1;t:update({pets={pip={xp={power=40,energy=20}}}})
  assert(queued[key].text=="Power 3, Energy 2","merged into the same line: "..queued[key].text)
  clock=2;t:update({pets={pip={xp={power=40,energy=20,heart=20,smarts=20}}}})
  local lines=0;for _ in pairs(queued)do lines+=1 end
  assert(lines==2,"a merge past the rail width starts its own line")
  -- A line that never showed is retired after MaxWait.
  clock=2+Toasts.MaxWait+1;t:update({pets={pip={xp={power=40,energy=20,heart=20,smarts=20,jump=20}}}})
  assert(t.handle.key~=key,"stale line retired")
 end)
 test("results parts: gains in Order, levelled flag from XP now",function()
  local parts=Toasts.resultsParts({power=24,energy=31,heart=1},{power=300,energy=31,heart=14})
  assert(#parts==3 and parts[1].id=="heart"and parts[2].id=="power"and parts[3].id=="energy")
  assert(parts[2].up==true and parts[2].level==10 and parts[2].text=="Power +24 (Lv 10!)",parts[2].text)
  assert(parts[1].up==true and parts[3].text=="Energy +31 (Lv 2!)")
  assert(#Toasts.resultsParts(nil,{})==0 and #Toasts.resultsParts({power=0},{})==0)
  assert(Toasts.resultsParts({power=5},nil)[1].text=="Power +5","no XP: no level claim")
 end)
 test("panel model, tiers and the next Keeper tier",function()
  local m=Panel.model({pets={pip={xp={power=300,heart=14}}},bonus={power=40}},"pip")
  assert(m.total==16 and m.stats[2].id=="power"and m.stats[2].level==10 and m.stats[2].bonus==40 and m.stats[1].bonus==0)
  assert(Panel.toNext(m.stats[2])=="45 XP to 11",Panel.toNext(m.stats[2]))
  assert(Panel.toNext({need=0,into=0,level=99})==Panel.toNext({need=0,into=5,level=99}))
  assert(Panel.keeperWord(6)=="Seedling Keeper"and Panel.keeperWord(300)=="Full Bloom Keeper"and Panel.keeperWord(594)=="Garden Star")
  local n=Panel.nextKeeper(10);assert(n.total==60 and n.from==6,"next is Sprout at 60")
  assert(Panel.nextKeeper(450).total==594 and Panel.nextKeeper(594)==nil)
  assert(Panel.model(nil,"pip").total==6,"no stats: a fresh sheet")
  assert(Panel.step(1,1,0)==2 and Panel.step(1,0,1)==4 and Panel.step(3,1,0)==3 and Panel.step(5,0,-1)==2,"3 x 2 grid")
 end)
 test("bonus tag fit and the focus row's Stats slot",function()
  local show,word=Panel.bonusFit(70,24,80);assert(show and word)
  show,word=Panel.bonusFit(70,24,40);assert(show and not word)
  show=Panel.bonusFit(70,24,20);assert(not show)
  -- Spencer 2026-11-20: Stats and Snacks stack at the bottom left (Snacks lowest).
  local wide=Row.layout(1600,150,false,true,true,900)
  assert(wide.snacks and wide.snacks.x==12 and wide.snacks.y+wide.snacks.h==900-12,"Snacks at the bottom left")
  assert(wide.stats and wide.stats.x==12 and wide.stats.y+wide.stats.h+wide.gap==wide.snacks.y,"Stats just above Snacks")
  local short=Row.layout(844,150,false,true,true,130);assert(short.snacks and short.stats==nil,"no room for both")
  assert(Row.layout(1600,150,false,true,true).stats==nil,"no height: hidden")
  assert(Row.layout(1600,150,false,nil,nil,900).stats==nil,"no button asked for")
 end)
 return cases
end
