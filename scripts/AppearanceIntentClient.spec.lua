-- Deterministic transport clock, no remotes/profile writes.
return function(client)
 local Intent=require(client.AppearanceIntent);local cases={}
 local function test(name,body)body();table.insert(cases,name)end
 local function fixture()
  local f={time=0,sends={},changes=0}
  f.i=Intent.new({themeId="sherbet",stickerId="none",revision=0,now=function()return f.time end,
   send=function(p)table.insert(f.sends,table.clone(p))end,changed=function()f.changes+=1 end,
   delay=function()return {}end,cancel=function()end})
  function f:at(t)self.time=t;self.i:step()end
  function f:reply(slot,seq,id,status,rev,theme,sticker,reason,extra)
   local r={slot=slot,seq=seq,id=id,status=status,revision=rev or 0,themeId=theme or "sherbet",stickerId=sticker or "none",reason=reason}
   for k,v in pairs(extra or {})do r[k]=v end;self.i:receive(r)
  end
  return f
 end
 test("independent slots globally paced with latest unsent sticker",function()
  local f=fixture();f.i:choose("theme","brick");f.i:choose("sticker","star");f.i:choose("sticker","seed")
  assert(#f.sends==1);f:at(.27);assert(#f.sends==2 and f.sends[2].id=="seed"and f.sends[2].seq==2);f.i:destroy()
 end)
 test("Applied is confirmed but not durable until matching Saved",function()
  local f=fixture();f.i:choose("theme","brick");f:reply("theme",1,"brick","Applied",1,"brick")
  assert(f.i:view().confirmedTheme=="brick"and f.i:view().slots.theme.status=="Applied")
  f:reply("theme",1,"brick","Saved",1,"brick");assert(f.i:view().slots.theme.status=="Saved");f.i:destroy()
 end)
 test("rapid same-slot choices coalesce behind accepted old request",function()
  local f=fixture();f.i:choose("theme","brick");f.i:choose("theme","ice");f.i:choose("theme","stone")
  f:reply("theme",1,"brick","Applied",1,"brick");f:at(.27)
  assert(#f.sends==2 and f.sends[2].id=="stone"and f.i:view().themeId=="stone");f.i:destroy()
 end)
 test("late lower-revision sibling cannot roll back atomic pair",function()
  local f=fixture();f.i:choose("theme","brick");f.i:choose("sticker","star");f:at(.27)
  f:reply("sticker",1,"star","Applied",2,"brick","star");f:reply("theme",1,"brick","Applied",1,"brick","none")
  assert(f.i:view().confirmedSticker=="star"and f.i.revision==2);f.i:destroy()
 end)
 test("throttle retries identical seq only after retryAfter",function()
  local f=fixture();f.i:choose("theme","ice");f:reply("theme",1,"ice","Rejected",0,nil,nil,"Throttled",{retryAfter=.6})
  f:at(.59);assert(#f.sends==1);f:at(.61);assert(#f.sends==2 and f.sends[2].seq==1);f.i:destroy()
 end)
 test("new choice cancels queued throttled retry",function()
  local f=fixture();f.i:choose("theme","ice");f:reply("theme",1,"ice","Rejected",0,nil,nil,"Throttled",{retryAfter=.6})
  f.i:choose("theme","brick");f:at(.27);assert(#f.sends==2 and f.sends[2].id=="brick");f.i:destroy()
 end)
 test("missing reply uses same seq max three then explicit Retry",function()
  local f=fixture();f.i:choose("sticker","star");f:at(1.51);f:at(3.02);f:at(4.53)
  assert(#f.sends==3 and f.i:view().slots.sticker.status=="Retry")
  assert(f.i:retry("sticker")and #f.sends==4 and f.sends[4].seq==1);f.i:destroy()
 end)
 test("late Saved resolves timed-out desired without manual resend",function()
  local f=fixture();f.i:choose("sticker","star");f:at(1.51);f:at(3.02);f:at(4.53)
  f:reply("sticker",1,"star","Saved",1,nil,"star")
  assert(f.i:view().slots.sticker.status=="Saved"and f.i:view().confirmedSticker=="star"and #f.sends==3);f.i:destroy()
 end)
 test("compensating confirmed choice after lost reply sends newer sequence",function()
  local f=fixture();f.i:choose("sticker","star");f:at(1.51);f:at(3.02);f:at(4.53)
  assert(f.i:choose("sticker","none"));assert(f.sends[4].id=="none"and f.sends[4].seq==2)
  f:reply("sticker",1,"star","Applied",1,nil,"star");assert(f.i:view().stickerId=="none")
  f:reply("sticker",2,"none","Applied",2,nil,"none");assert(f.i:view().confirmedSticker=="none");f.i:destroy()
 end)
 test("Superseded after Applied adopts foreign pair and never resends old",function()
  local f=fixture();f.i:choose("theme","brick");f:reply("theme",1,"brick","Applied",1,"brick")
  f:reply("theme",1,"brick","Rejected",2,"ice","star","Superseded");f:at(10)
  assert(f.i:view().confirmedTheme=="ice"and f.i:view().confirmedSticker=="star"and f.i:view().slots.theme.reason=="Superseded"and #f.sends==1)
  assert(not f.i:retry("theme"));f.i:destroy()
 end)
 test("old Superseded and Saved cannot terminate newer local intent",function()
  local f=fixture();f.i:choose("theme","brick");f:reply("theme",1,"brick","Applied",1,"brick");f.i:choose("theme","stone")
  f:reply("theme",1,"brick","Rejected",2,"ice",nil,"Superseded");f:reply("theme",1,"brick","Saved",1,"brick")
  assert(f.i:view().themeId=="stone"and f.i:view().slots.theme.status=="Pending"and f.i:view().confirmedTheme=="ice");f.i:destroy()
 end)
 test("stale newest intent rebases from lastSeq in bounded session",function()
  local f=fixture();f.i:choose("theme","brick");f:reply("theme",1,"brick","Rejected",1,"ice",nil,"Stale",{lastSeq=8});f:at(.27)
  assert(#f.sends==2 and f.sends[2].seq==9 and f.sends[2].id=="brick");f.i:destroy()
 end)
 test("Locked rejection reconciles and cannot retry old locked item",function()
  local f=fixture();f.i:choose("sticker","wick");f:reply("sticker",1,"wick","Rejected",0,nil,nil,"Locked")
  assert(f.i:view().stickerId=="none"and not f.i:retry("sticker"));f.i:destroy()
 end)
 test("view snapshots and repeated identical authoritative pair send nothing",function()
  local f=fixture();for _=1,5 do f.i:view();f.i:snapshot("sherbet","none",0)end
  assert(#f.sends==0 and f.changes==1);f.i:destroy();assert(not f.i:choose("theme","brick"));f:at(20);assert(#f.sends==0)
 end)
 test("three independent latest slots serialize without losing sibling intent",function()
  local f=fixture();f.i:choose("theme","brick");f.i:choose("sticker","star");f.i:choose("background","creek");f.i:choose("background","lantern")
  f:at(.27);f:at(.54);assert(#f.sends==3 and f.sends[3].slot=="background"and f.sends[3].id=="lantern"and f.sends[3].seq==2)
  f.i:receive({slot="background",seq=2,id="lantern",status="Applied",revision=3,themeId="brick",stickerId="star",backgroundId="lantern"})
  assert(f.i:view().confirmedBackground=="lantern"and f.i:view().slots.background.status=="Applied");f.i:destroy()
 end)
 test("background timeout resends same identity and matching Saved alone proves durability",function()
  local f=fixture();f.i:choose("background","creek");f:at(1.51);assert(f.sends[1].seq==f.sends[2].seq)
  f.i:receive({slot="background",seq=1,id="creek",status="Saved",revision=1,themeId="sherbet",stickerId="none",backgroundId="creek"})
  assert(f.i:view().confirmedBackground=="creek"and f.i:view().slots.background.status=="Saved");f.i:destroy()
 end)
 test("older pair-shaped reply cannot reset newer accepted background",function()
  local f=fixture();f.i:choose("background","lantern")
  f.i:receive({slot="background",seq=1,id="lantern",status="Applied",revision=4,themeId="ice",stickerId="star",backgroundId="lantern"})
  f:reply("theme",1,"brick","Saved",1,"brick","none")
  assert(f.i:view().confirmedBackground=="lantern"and f.i:view().confirmedTheme=="ice")
  f:reply("sticker",1,"star","Saved",5,"ice","star")
  assert(f.i:view().confirmedBackground=="lantern");f.i:destroy()
 end)
 test("old background Saved cannot make a newer background choice durable",function()
  local f=fixture();f.i:choose("background","creek")
  f.i:receive({slot="background",seq=1,id="creek",status="Applied",revision=1,themeId="sherbet",stickerId="none",backgroundId="creek"})
  f.i:choose("background","canopy")
  f.i:receive({slot="background",seq=1,id="creek",status="Saved",revision=1,themeId="sherbet",stickerId="none",backgroundId="creek"})
  assert(f.i:view().backgroundId=="canopy"and f.i:view().slots.background.status=="Pending");f.i:destroy()
 end)
 test("unknown fallback marker is read-only; absent old field is ordinary default",function()
  local f=fixture();assert(not f.i:setFallbacks({}));assert(f.i:setFallbacks({background="Unknown",bad="Unknown"}));assert(#f.sends==0 and f.i:view().fallbacks.background=="Unknown"and not f.i:view().fallbacks.bad)
  assert(f.i:choose("background","canopy")and #f.sends==1 and f.sends[1].seq==1)
  assert(not f.i:choose("background","canopy")and #f.sends==1);f.i:destroy()
 end)
 test("fallback correction becomes Saved only from correlated proof and marker removal",function()
  local f=fixture();f.i:setFallbacks({background="Locked"});f.i:choose("background","canopy")
  f.i:receive({slot="background",seq=1,id="canopy",status="Applied",revision=1,themeId="sherbet",stickerId="none",backgroundId="canopy"})
  assert(f.i:view().slots.background.status~="Saved")
  f.i:setFallbacks({});assert(f.i:view().slots.background.status=="Applied")
  f.i:receive({slot="background",seq=1,id="canopy",status="Saved",revision=1,themeId="sherbet",stickerId="none",backgroundId="canopy"})
  assert(f.i:view().slots.background.status=="Saved"and #f.sends==1);assert(not f.i:choose("background","canopy"));f.i:destroy()
 end)
 test("other-slot durability can clear fallback without fabricating background acknowledgement",function()
  local f=fixture();f.i:setFallbacks({background="Unknown"});f.i:choose("theme","brick")
  f.i:receive({slot="theme",seq=1,id="brick",status="Saved",revision=1,themeId="brick",stickerId="none",backgroundId="canopy"});f.i:setFallbacks({})
  assert(f.i:view().slots.background.status=="Ready"and not f.i:view().fallbacks.background and #f.sends==1);f.i:destroy()
 end)
 test("QA Q2.4: shown() wears a choice in flight at once and falls back to confirmed on a refusal",function()
  local f=fixture();f.i:choose("theme","brick")
  assert(Intent.shown(f.i:view(),"theme")=="brick"and f.i:view().confirmedTheme=="sherbet","optimistic while Pending")
  f:reply("theme",1,"brick","Rejected",0,"sherbet","none","Locked")
  assert(Intent.shown(f.i:view(),"theme")=="sherbet","rolled back")
  -- A real Applied reply carries the server's post-apply snapshot (server AppearanceIntent
  -- snapshot(profile)), so it names "ice" at a newer revision; an Applied paired with an
  -- older look is the stale/superseded case the view reports as Ready (QA Q2.4 spec fix).
  f.i:choose("theme","ice");f:reply("theme",2,"ice","Applied",1,"ice","none")
  assert(Intent.shown(f.i:view(),"theme")=="ice","Applied before the snapshot still shows the new look")
  assert(Intent.shown(nil,"theme")==nil and Intent.shown({confirmedBackground="creek",slots={}},"background")=="creek")
  f.i:destroy()
 end)
 return{passed=#cases,cases=cases}
end
