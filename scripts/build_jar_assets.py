"""Customization Egg jar art in the game (slice 3, 2026-11-16).

Reads assets/art-source/jars/customization-jars-meshids.json (the uploaded Model, read back
with InsertService:LoadAsset) and customization-jars-parts.json (Blender colours and alpha),
and writes:
  assets/jars/JarAssets.rbxmx       ReplicatedStorage.JarAssets: one template MeshPart per mesh
  src/client/JarModelData.lua       per jar: its parts' mesh, size, position, colour, look

One colour per part (MeshParts draw no vertex colours). Liquids take the HueCatalog pigment;
the Citrus lemon is drawn near white over a deeper gold so it reads on yellow (QA 2026-11-16c).
Usage (from the repo root): python scripts/build_jar_assets.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
JARS = os.path.join(ROOT, "assets", "art-source", "jars")
OUT_RBXMX = os.path.join(ROOT, "assets", "jars", "JarAssets.rbxmx")
OUT_LUA = os.path.join(ROOT, "src", "client", "JarModelData.lua")

PIGMENT = {"rose": "#FF327A", "tide": "#008DFF", "citrus": "#FFB300", "iris": "#9350FF", "reset": "#4FB9CC"}
# part -> (transparency, material, reflectance); colour from the Blender mean unless overridden
LOOK = {
    "Body": (.72, "SmoothPlastic", 0),
    # pass 4: a closed see-through volume drawn DoubleSided (JarModel), so the pigment is two
    # layers deep round the symbol and one layer in front of it: vivid, and the symbol shows
    "Liquid": (.48, "SmoothPlastic", 0),
    "Symbol": (0, "SmoothPlastic", 0),
    "Lid": (0, "SmoothPlastic", 0),
    "Shine": (.15, "SmoothPlastic", 0),
    "Topper": (0, "SmoothPlastic", 0),
    "Core": (0, "SmoothPlastic", 0),
    "Base": (0, "SmoothPlastic", 0),
    "Dome": (.6, "SmoothPlastic", 0),
    "Charm": (0, "Neon", 0),
    "Loop": (0, "SmoothPlastic", 0),
}
SPECIAL = {
    ("gloss", "Body"): ("#58DDC2", 0, "SmoothPlastic", .3),
    ("matte", "Body"): ("#7FD8C6", 0, "Sand", 0),
    ("matte", "Topper"): ("#E9FFF9", 0, "Sand", 0),
    ("jelly", "Body"): ("#58DDC2", .3, "SmoothPlastic", .05),
    ("citrus", "Symbol"): ("#FFFFFF", 0, "SmoothPlastic", 0),  # stronger contrast on yellow (QA 2026-11-16c)
    ("charm", "Charm"): ("#FFCB3D", 0, "SmoothPlastic", 0),
}
PART = """    <Item class="MeshPart" referent="{name}">
      <Properties>
        <string name="Name">{name}</string>
        <Content name="MeshId"><url>{mesh}</url></Content>
        <Content name="TextureID"><url /></Content>
        <Vector3 name="Size"><X>{x}</X><Y>{y}</Y><Z>{z}</Z></Vector3>
        <Vector3 name="InitialSize"><X>{x}</X><Y>{y}</Y><Z>{z}</Z></Vector3>
        <bool name="Anchored">true</bool>
        <bool name="CanCollide">false</bool>
        <bool name="CanTouch">false</bool>
        <bool name="CanQuery">false</bool>
        <bool name="CastShadow">false</bool>
        <token name="CollisionFidelity">1</token>
      </Properties>
    </Item>
"""


def look(item, part, mean_colour):
    """In-game look of one part: (hex colour, transparency, material, reflectance).
    Shared with scripts/render_customization_jars_turntable.py so the renders match the game."""
    transparency, material, reflectance = LOOK.get(part, (0, "SmoothPlastic", 0))
    colour = mean_colour or "#FFFFFF"
    if part == "Liquid":
        colour = PIGMENT.get(item, colour)
    if part == "Shine":
        colour = "#FFFFFF"
    if part == "Lid" or part == "Loop":
        colour = "#FFF3D6"
    if (item, part) in SPECIAL:
        colour, transparency, material, reflectance = SPECIAL[(item, part)]
    return colour, transparency, material, reflectance


def main():
    ids = json.load(open(os.path.join(JARS, "customization-jars-meshids.json"), encoding="utf-8"))
    parts = {p["name"]: p for p in json.load(open(os.path.join(JARS, "customization-jars-parts.json"), encoding="utf-8"))["parts"]}
    rows = ['<roblox version="4">\n  <Item class="Folder" referent="JarAssets">\n    <Properties>\n'
            '      <string name="Name">JarAssets</string>\n    </Properties>\n']
    items = {}
    for name in sorted(ids["meshes"]):
        mesh, size, pos = ids["meshes"][name]
        rows.append(PART.format(name=name, mesh=mesh, x=size[0], y=size[1], z=size[2]))
        item, part = name[4:].split("__", 1)
        colour, transparency, material, reflectance = look(item, part, parts[name]["colour"])
        items.setdefault(item, []).append((name, part, size, pos, colour, transparency, material, reflectance))
    rows.append("  </Item>\n</roblox>\n")
    os.makedirs(os.path.dirname(OUT_RBXMX), exist_ok=True)
    with open(OUT_RBXMX, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(rows))
    lua = ["-- Generated by scripts/build_jar_assets.py from assets/art-source/jars/customization-jars-meshids.json.",
           "-- Do not edit by hand. Studs (100x Blender units); every jar built at the origin, front facing -Z.",
           "-- Asset %d (Model). %s" % (ids["asset"], ids["moderation"]),
           "local function v(x,y,z)return Vector3.new(x,y,z)end",
           "return table.freeze({Asset=%d,Items=table.freeze({" % ids["asset"]]
    for item in sorted(items):
        lua.append(" %s=table.freeze({" % item)
        for name, part, size, pos, colour, transparency, material, reflectance in items[item]:
            lua.append('  table.freeze({name="%s",part="%s",size=v(%g,%g,%g),position=v(%g,%g,%g),color="%s",transparency=%g,material="%s",reflectance=%g}),'
                       % (name, part, size[0], size[1], size[2], pos[0], pos[1], pos[2], colour, transparency, material, reflectance))
        lua.append(" }),")
    lua.append("})})")
    with open(OUT_LUA, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lua) + "\n")
    print("wrote", OUT_RBXMX, len(ids["meshes"]), "meshes;", OUT_LUA, len(items), "jars")


if __name__ == "__main__":
    main()
