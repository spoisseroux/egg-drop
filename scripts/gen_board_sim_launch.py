"""Generate src/shared/BoardSimLaunch.lua: the deterministic board sim's literal tables.

B0 of the client-run board (artifacts/qa-2026-11-17-v887/B0-plan.md). The shared sim
(src/shared/BoardSim.lua) must step identically on the server and on every client, so it
never calls math.sin/cos at runtime: the launch velocity for each aim on a fixed grid, and
every per-step constant, are written here as exact doubles (%.17g round-trips a double).

Mirrors BoardConfig: LaunchAngleDegrees, LaunchSpeed, Gravity, FixedStep, the 0.85/s drag.
Re-run after changing any of them:  python scripts/gen_board_sim_launch.py
"""
import math
import os

AIM_STEPS = 400
LAUNCH_ANGLE_DEGREES = 35
LAUNCH_SPEED = 10
GRAVITY = 32
FIXED_STEP = 1 / 120
DRAG_PER_SECOND = 0.85


def lit(value: float) -> str:
    text = "%.17g" % value
    assert float(text) == value, text
    if text == "-0":
        text = "0"
    return text


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "src", "shared", "BoardSimLaunch.lua")
    radians = math.radians(LAUNCH_ANGLE_DEGREES)
    rows = []
    for index in range(AIM_STEPS + 1):
        aim = index / AIM_STEPS
        angle = (aim * 2 - 1) * radians
        vx = math.sin(angle) * LAUNCH_SPEED
        vy = -math.cos(angle) * LAUNCH_SPEED
        rows.append("{%s,%s}" % (lit(vx), lit(vy)))
    lines = [
        "-- GENERATED by scripts/gen_board_sim_launch.py. Do not edit by hand.",
        "-- Literal tables for the deterministic board sim (BoardSim, B0 client-run board):",
        "-- launch velocity per aim index (aim = index / AimSteps, index 0..AimSteps), and the",
        "-- per-fixed-step constants, so no libm call or float32 rounding runs in the step.",
        "local Launch={}",
        "Launch.AimSteps=%d" % AIM_STEPS,
        "Launch.Speed=%d -- BoardConfig.LaunchSpeed" % LAUNCH_SPEED,
        "Launch.AngleDegrees=%d -- BoardConfig.LaunchAngleDegrees" % LAUNCH_ANGLE_DEGREES,
        "Launch.Dt=%s -- BoardConfig.FixedStep" % lit(FIXED_STEP),
        "Launch.GravityDt=%s -- Gravity * Dt" % lit(GRAVITY * FIXED_STEP),
        "Launch.Drag=%s -- 1 - Dt * 0.85" % lit(1 - FIXED_STEP * DRAG_PER_SECOND),
        "Launch.Diagonal=%s -- 1 / sqrt(2)" % lit(1 / math.sqrt(2)),
        "-- {vx, vy} for index 0..AimSteps, stored 1-based (Velocity[index + 1]).",
        "Launch.Velocity={",
    ]
    for start in range(0, len(rows), 4):
        lines.append(" " + ",".join(rows[start:start + 4]) + ",")
    lines.append("}")
    lines.append("for _,row in ipairs(Launch.Velocity)do table.freeze(row)end")
    lines.append("table.freeze(Launch.Velocity)")
    lines.append("return table.freeze(Launch)")
    with open(out, "w", encoding="utf-8", newline="") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote", out, len(rows), "aims")


if __name__ == "__main__":
    main()
