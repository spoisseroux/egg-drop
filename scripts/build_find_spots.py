"""Write src/shared/FindSpots.lua: the Garden finds spots (V3-FINDS-BUILD-PLAN-2026-11-22, slice S9).

Six spots on each of four lawns, from the walk map (assets/world/world-v7-walk.json) and the same solid things the
Dash course builder keeps clear of. A spot is grass ("G") for 2 studs round, nearly level, at least KEEP studs from
the stations, lamps, park kerbs, the grove, bushes, flower patches and water, and clear of every Garden Dash lane
and the waiting pad. Inside a lawn the six are spread out (farthest-point from a fixed seed). Fails if a lawn has
fewer than six. Heights are World.groundY's; the Studio check raycasts the result.

    python scripts/build_find_spots.py          write the module
    python scripts/build_find_spots.py --check  fail when the committed module differs
"""
import math
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_dash_course as D  # noqa: E402  (the walk map and the measured solid things)

ROOT = D.ROOT
OUT = ROOT / "src/shared/FindSpots.lua"
PER_LAWN = 6
KEEP = 6.0
LEVEL = .6  # most height change across a 4-stud disc (about 15 degrees)
# WORLD-PLAN-2026-11-22 section 2: x0, x1, z0, z1.
LAWNS = [
    ("south", 56, 88, 68, 82),
    ("east", 18, 46, -28, -10),
    ("west", -100, -75, 8, 35),
    ("grove", -88, -58, -58, -28),
]
SPAWN = (96.0, 66.0)


def lua_points(name):
    text = (ROOT / "src/shared/DashCourse.lua").read_text()
    block = text.split(f"Course.{name}=table.freeze(")[1].split("\nCourse.")[0]
    return [(int(x) / 100, int(z) / 100) for x, z in re.findall(r"x=(-?\d+),y=-?\d+,z=(-?\d+)", block)]


COURSE = lua_points("Main") + lua_points("Branch") + lua_points("Stones")
FLOWERS = [(float(x), float(z)) for x, z in re.findall(
    r"\{(-?[\d.]+),-?[\d.]+,(-?[\d.]+),", (ROOT / "src/shared/WorldDressing.lua").read_text().split("Dressing.Flowers=")[1].split("Dressing.")[0])]
PAD = (D.PAD[0], D.PAD[1], D.PAD_RADIUS)


def grass(x, z, r=2):
    return all(D.code(x + a, z + b)[0] == "G" for a in range(-r, r + 1) for b in range(-r, r + 1) if a * a + b * b <= r * r)


def level(x, z):
    heights = [D.ground(x + 2 * math.cos(k * math.pi / 4), z + 2 * math.sin(k * math.pi / 4)) for k in range(8)] + [D.ground(x, z)]
    return max(heights) - min(heights) <= LEVEL and min(heights) > -100


def clear(x, z):
    p = (x, z)
    near = lambda points, room: all(math.dist(p, q) >= room for q in points)
    return (near(D.STATIONS, KEEP + 3) and near(D.LAMPS, KEEP) and near(D.BUSHES, KEEP - 2) and near(FLOWERS, KEEP - 2)
            and near(COURSE, KEEP + D.LANES / 2 * D.LANE_STEP) and math.dist(p, PAD[:2]) >= PAD[2] + KEEP
            and all(math.dist(p, o[:2]) >= o[2] + KEEP for o in D.OBSTACLES)
            and D.kerb_distance(x, z) >= KEEP and D.grove_distance(x, z) >= KEEP
            and not any(D.in_box(x, z, box, KEEP) for box in D.WET + D.BLOCKED)
            and not D.on_span(x, z, -KEEP) and math.dist(p, SPAWN) >= 12)


def lawn_spots(name, x0, x1, z0, z1):
    ok = [(x, z) for x in range(x0, x1 + 1) for z in range(z0, z1 + 1) if grass(x, z) and level(x, z) and clear(x, z)]
    if len(ok) < PER_LAWN:
        raise SystemExit(f"{name}: only {len(ok)} cells pass")
    cx, cz = (x0 + x1) / 2, (z0 + z1) / 2
    chosen = [min(ok, key=lambda c: (math.dist(c, (cx, cz)), c))]
    while len(chosen) < PER_LAWN:
        chosen.append(max(ok, key=lambda c: (min(math.dist(c, q) for q in chosen), -c[0], -c[1])))
    return sorted(chosen), len(ok)


def emit(spots):
    rows = []
    for name, points, _ in spots:
        for x, z in points:
            y = round(D.ground(x, z) * 100)
            rows.append(f"\ttable.freeze({{lawn=\"{name}\",x={x * 100},y={y},z={z * 100}}}),")
    counts = ", ".join(f"{name} {n}" for name, _, n in spots)
    return (
        "-- Generated by scripts/build_find_spots.py from assets/world/world-v7-walk.json; do not edit by hand.\n"
        "-- Garden finds (V3-FINDS-BUILD-PLAN-2026-11-22): six spots a lawn, in hundredths of a stud (x, ground y, z).\n"
        f"-- Cells that passed every rule: {counts}.\n"
        "return table.freeze({\n" + "\n".join(rows) + "\n})\n"
    )


def main():
    spots = []
    for lawn in LAWNS:
        points, n = lawn_spots(*lawn)
        spots.append((lawn[0], points, n))
    text = emit(spots)
    if "--check" in sys.argv:
        if OUT.read_bytes().decode().replace("\r\n", "\n") != text:
            raise SystemExit("FindSpots.lua is stale: rerun scripts/build_find_spots.py")
        print("FindSpots.lua is current")
        return
    OUT.write_text(text, encoding="utf-8", newline="\r\n")
    print(text)


if __name__ == "__main__":
    main()
