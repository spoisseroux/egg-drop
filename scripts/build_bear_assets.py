"""Build the Bear's runtime rig definition and its PetAssets template from the export + Studio import.

Inputs (both in assets/garden-babies/):
- bear-export-manifest.json: Blender pet-local bounding boxes and anchors (front -Y, up +Z, L = -X).
- bear-studio-import.json: mesh asset IDs, raw 100x MeshSize, and uploaded texture IDs.

Outputs:
- src/shared/BearRigDefinition.lua: definition in the runtime axes (front +Z, up +Y), used for
  pet id `pip`. twoTone=true turns on the two-colour body (PET-STYLE-GUIDE.md).
- PetAssets.rbxmx: the `Bear` Model between the BEAR markers. Template axes are the import's
  (front -Z); GardenPetVisual turns it by pi once. Size = MeshSize/100, InitialSize = raw MeshSize.

Blender (x, y, z) maps to template (-x, z, y) and to definition (x, z, -y); this was checked against
the actual Studio import (worst centre difference 0.000005 studs).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "garden-babies"
EXPORT = json.loads((ASSETS / "bear-export-manifest.json").read_text())
IMPORT = json.loads((ASSETS / "bear-studio-import.json").read_text())

# name -> (channel, colorRole, native fallback shape). Wings and alt charms are imported but not
# part of the default pet: wings come from an egg, charms from the Charm Egg.
PIECES = {
    "Body": ("Body", "body", "ellipsoid"),
    "Head": ("Head", "body", "ellipsoid"),
    "EarL": ("Head", "body", "ellipsoid"),
    "EarR": ("Head", "body", "ellipsoid"),
    "EarInnerL": ("Head", "secondary", "ellipsoid"),
    "EarInnerR": ("Head", "secondary", "ellipsoid"),
    "Muzzle": ("Head", "secondary", "ellipsoid"),
    "Nose": ("Head", "face", "ellipsoid"),
    "MouthSmile": ("Head", "mouth", "smile"),
    "EyeL": ("Head", "face", "ellipsoid"),
    "EyeR": ("Head", "face", "ellipsoid"),
    "Tail": ("Body", "body", "ellipsoid"),
    "HandL": ("HandL", "body", "ellipsoid"),
    "HandR": ("HandR", "body", "ellipsoid"),
    "FootL": ("FootL", "body", "ellipsoid"),
    "FootR": ("FootR", "body", "ellipsoid"),
    "CharmDot": ("Charm", "secondary", "ellipsoid"),
}
TEMPLATE_EXTRA = ("WingL", "WingR", "CharmStar", "CharmHeart", "CharmButton")
ANCHORS = {"Head": "Head", "Body": "Body", "HandL": "HandL", "HandR": "HandR", "FootL": "FootL", "FootR": "FootR",
           "EyeLine": "EyeLine", "HandCatch": "HandCatch", "CharmAnchor": "CharmFloat", "Tail": "Tail",
           "EarL": "EarL", "EarR": "EarR", "WingL": "WingL", "WingR": "WingR",
           "CharmLeft": "CharmLeft", "CharmRight": "CharmRight", "CharmCenter": "CharmCenter", "CharmFloat": "CharmFloat"}


def to_def(c):
    return [round(c[0], 6), round(c[2], 6), round(-c[1], 6)]


def to_template(c):
    return (-c[0], c[2], c[1])


def size_of(s):
    return [round(s[0], 6), round(s[2], 6), round(s[1], 6)]


def lua_definition() -> str:
    objects = {o["name"].split("__", 1)[1]: o for o in EXPORT["objects"]}
    pieces = []
    for name, (channel, role, shape) in PIECES.items():
        o = objects[name]
        pieces.append({"name": name, "channel": channel, "shape": shape, "center": to_def(o["centerBlender"]),
                       "size": size_of(o["sizeBlender"]), "xyzEulerDeg": [0, 0, 0], "colorRole": role})
    # Surprise mouth: a small dark "O" the runtime draws itself (no mesh), seated on the front of the muzzle (the smile is a curved shell, so its centre is inside it).
    mouth = next(p for p in pieces if p["name"] == "MouthSmile")
    pieces.append({"name": "MouthO", "channel": "Head", "shape": "ellipsoid",
                   "center": [mouth["center"][0], mouth["center"][1], round(mouth["center"][2] + mouth["size"][2] / 2 - 0.015, 6)],
                   "size": [0.07, 0.08, 0.03], "xyzEulerDeg": [0, 0, 0], "colorRole": "mouth"})
    anchors = {"Root": [0, 0, 0]}
    for key, src in ANCHORS.items():
        anchors[key] = to_def(EXPORT["anchorsBlender"][src])
    definition = {
        "schema": 1, "id": "bear", "legacyId": "pip", "twoTone": True,
        "axes": {"up": "+Y", "front": "+Z", "right": "+X"}, "units": "studs at garden size",
        "nativeScaleFactor": 1.3888888888888888,
        "palette": {"body": "#FFFFFF", "secondary": "#C8C8C8", "face": "#2A2226", "mouth": "#66332E",
                    "ivory": "#FFF6E9", "blush": "#E8A6A6"},
        "anchors": anchors, "pieces": pieces,
    }
    body = json.dumps(definition, separators=(",", ":"))
    return ("-- Generated by scripts/build_bear_assets.py from the Bear export and Studio import. Do not edit by hand.\n"
            "-- Runtime axes: front +Z, up +Y, paws at the origin. twoTone turns on the two-colour body.\n"
            f"return game:GetService(\"HttpService\"):JSONDecode([=[{body}]=])\n")


def vec(tag, v):
    return f"          <Vector3 name=\"{tag}\">\n            <X>{v[0]!r}</X>\n            <Y>{v[1]!r}</Y>\n            <Z>{v[2]!r}</Z>\n          </Vector3>\n"


def xml_block() -> str:
    objects = {o["name"]: o for o in EXPORT["objects"]}
    parts = IMPORT["parts"]
    textures = IMPORT["textures"]
    charm = to_template(objects["Bear__CharmDot"]["centerBlender"])
    out = ["    <!-- BEGIN BEAR (generated by scripts/build_bear_assets.py) -->\n",
           "    <Item class=\"Model\" referent=\"Bear\">\n      <Properties>\n        <string name=\"Name\">Bear</string>\n      </Properties>\n",
           "      <Item class=\"CFrameValue\" referent=\"BearOrigin\">\n        <Properties>\n          <string name=\"Name\">PawsOrigin</string>\n"
           "          <CoordinateFrame name=\"Value\">\n            <X>0</X>\n            <Y>0</Y>\n            <Z>0</Z>\n"
           "            <R00>1</R00>\n            <R01>0</R01>\n            <R02>0</R02>\n            <R10>0</R10>\n            <R11>1</R11>\n"
           "            <R12>0</R12>\n            <R20>0</R20>\n            <R21>0</R21>\n            <R22>1</R22>\n          </CoordinateFrame>\n"
           "        </Properties>\n      </Item>\n"]
    for index, name in enumerate(list(PIECES) + list(TEMPLATE_EXTRA)):
        key = "Bear__" + name
        o, p = objects[key], parts[key]
        pos = charm if name in ("CharmStar", "CharmHeart", "CharmButton") else to_template(o["centerBlender"])
        raw = p["ms"]
        size = [raw[0] / 100, raw[1] / 100, raw[2] / 100]
        # Cut-out textures (the mouth) need a SurfaceAppearance in Transparency mode:
        # MeshPart.TextureID ignored the mouth's alpha in-game (checked in Studio 2026-11-12).
        cutout = textures.get(name, "") if name == "MouthSmile" else ""
        texture = "" if cutout else textures.get(name, "")
        ink = ("        <Item class=\"SurfaceAppearance\" referent=\"BearInk\">\n          <Properties>\n"
               "            <string name=\"Name\">MouthInk</string>\n            <token name=\"AlphaMode\">1</token>\n"
               f"            <Content name=\"ColorMap\">\n              <url>{cutout}</url>\n            </Content>\n"
               "          </Properties>\n        </Item>\n") if cutout else ""
        out.append(f"      <Item class=\"MeshPart\" referent=\"Bear{index}\">\n        <Properties>\n"
                   f"          <string name=\"Name\">{key}</string>\n"
                   f"          <Content name=\"MeshId\">\n            <url>{p['id']}</url>\n          </Content>\n"
                   f"          <Content name=\"TextureID\">\n            " + (f"<url>{texture}</url>" if texture else "<url />") + "\n          </Content>\n"
                   + vec("Size", size) + vec("InitialSize", raw) +
                   "          <CoordinateFrame name=\"CFrame\">\n"
                   f"            <X>{pos[0]!r}</X>\n            <Y>{pos[1]!r}</Y>\n            <Z>{pos[2]!r}</Z>\n"
                   "            <R00>1</R00>\n            <R01>0</R01>\n            <R02>0</R02>\n            <R10>0</R10>\n            <R11>1</R11>\n"
                   "            <R12>0</R12>\n            <R20>0</R20>\n            <R21>0</R21>\n            <R22>1</R22>\n          </CoordinateFrame>\n"
                   "          <bool name=\"Anchored\">true</bool>\n          <bool name=\"CanCollide\">false</bool>\n"
                   "          <bool name=\"CanTouch\">false</bool>\n          <bool name=\"CanQuery\">false</bool>\n"
                   "        </Properties>\n" + ink + "      </Item>\n")
    out.append("    </Item>\n    <!-- END BEAR -->\n")
    return "".join(out)


def main() -> None:
    (ROOT / "src" / "shared" / "BearRigDefinition.lua").write_text(lua_definition(), newline="\n")
    path = ASSETS / "PetAssets.rbxmx"
    text = path.read_text()
    block = xml_block()
    if "<!-- BEGIN BEAR" in text:
        start = text.index("    <!-- BEGIN BEAR")
        end = text.index("<!-- END BEAR -->") + len("<!-- END BEAR -->\n")
        text = text[:start] + block + text[end:]
    else:
        marker = "    <!-- END FIVE AUTHORED BABIES -->\n"
        assert marker in text, "PetAssets.rbxmx layout changed"
        text = text.replace(marker, marker + block, 1)
    path.write_text(text, newline="\r\n")  # the file is CRLF
    print("wrote BearRigDefinition.lua and the Bear template")


if __name__ == "__main__":
    main()
